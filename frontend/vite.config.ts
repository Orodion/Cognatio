import { defineConfig } from 'vitest/config';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { fileURLToPath } from 'node:url';
import { existsSync, readFileSync } from 'node:fs';
import type { Plugin } from 'vite';

// Version of the application (root package.json) – shown on the settings page
const appVersion = (JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')) as { version: string }).version;

// Backend target of the dev proxy (it listens on 127.0.0.1 only); can be overridden via API_TARGET (E2E tests use their own ports)
const apiTarget = process.env.API_TARGET ?? 'http://127.0.0.1:4000';

// Licences of everything the app contains (generated by scripts/third-party-notices.mjs): served as
// /third-party-notices.txt in development and put into the build; skipped where the file is not part of the context
const noticesFile = fileURLToPath(new URL('../THIRD-PARTY-NOTICES.md', import.meta.url));
const thirdPartyNotices = (): Plugin => ({
  name: 'third-party-notices',
  configureServer(server) {
    server.middlewares.use('/third-party-notices.txt', (_req, res) => {
      res.setHeader('Content-Type', 'text/plain; charset=utf-8');
      res.end(readFileSync(noticesFile));
    });
  },
  generateBundle() {
    if (existsSync(noticesFile)) {
      this.emitFile({ type: 'asset', fileName: 'third-party-notices.txt', source: readFileSync(noticesFile) });
    }
  },
});

// https://vitejs.dev/config/
export default defineConfig({
  plugins: [react(), tailwindcss(), thirdPartyNotices()],
  define: { __APP_VERSION__: JSON.stringify(appVersion) },
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  build: {
    rolldownOptions: {
      output: {
        // Large libraries in separate files: they change rarely and stay in the browser cache after app updates.
        // Libraries of the lazily loaded pages (React Flow, dagre, html-to-image) stay with those pages.
        codeSplitting: {
          groups: [
            { name: 'react', test: /node_modules[\\/](react|react-dom|scheduler|react-router|react-router-dom)[\\/]/, priority: 3 },
            { name: 'apollo', test: /node_modules[\\/](@apollo|graphql|@wry|optimism|zen-observable|ts-invariant|symbol-observable)[\\/]/, priority: 2 },
            { name: 'i18n', test: /node_modules[\\/](i18next|react-i18next)[\\/]/, priority: 1 },
          ],
        },
      },
    },
  },
  server: {
    port: 3000,
    proxy: {
      '/graphql': {
        target: apiTarget,
        changeOrigin: true,
      },
      // REST upload and uploaded files
      '/api': {
        target: apiTarget,
        changeOrigin: true,
      },
      '/uploads': {
        target: apiTarget,
        changeOrigin: true,
      },
    },
  },
  test: {
    globals: true,
    environment: 'jsdom',
    setupFiles: './src/setupTests.ts',
    coverage: {
      include: ['src/**/*.{ts,tsx}'],
      exclude: ['src/**/__tests__/**', 'src/main.tsx', 'src/setupTests.ts'],
      reporter: ['text-summary', 'lcov', 'cobertura'],
      // Minimum coverage (applies with --coverage, i.e. in CI): a few points below the level of 2026-09-29
      // (lines 92 %, statements 90 %, branches 84 %, functions 83 %) – raise step by step with new tests
      thresholds: { lines: 88, statements: 85, branches: 78, functions: 78 },
    },
  },
});
